import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import type { HttpRequest, HttpResponse, Transport } from "./http.js";

/**
 * Fixture files hold one recorded request/response pair. Dates are left out of the key,
 * and the response's dates are shifted on replay, so a recording keeps working for
 * any travel dates.
 */
export interface Fixture {
  request: { method: string; url: string; body?: unknown };
  /** Dates in the recorded request, in order of appearance. */
  recorded_dates: string[];
  /** True when generated by scripts/synth-fixtures.ts rather than recorded live. */
  synthetic?: boolean;
  response: HttpResponse;
}

const DATE_RE = /^(\d{4}-\d{2}-\d{2})(T.*)?$/;

function walk(value: unknown, onString: (s: string) => string): unknown {
  if (typeof value === "string") return onString(value);
  if (Array.isArray(value)) return value.map((v) => walk(v, onString));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, walk((value as Record<string, unknown>)[k], onString)]),
    );
  }
  return value;
}

function canonicalUrl(raw: string): string {
  const u = new URL(raw);
  u.searchParams.sort();
  return u.toString();
}

/** Dates found in the request URL and body, in order. */
export function requestDates(req: HttpRequest): string[] {
  const dates: string[] = [];
  const collect = (s: string) => {
    const m = DATE_RE.exec(s);
    if (m?.[1]) dates.push(m[1]);
    return s;
  };
  for (const v of new URL(req.url).searchParams.values()) collect(v);
  walk(req.body, collect);
  return dates;
}

/** Canonical form of a request without its dates. Headers (and so secrets) are excluded. */
export function fixtureKeyMaterial(req: HttpRequest): Fixture["request"] {
  const undated = (s: string) => (DATE_RE.test(s) ? "<date>" : s);
  const url = new URL(canonicalUrl(req.url));
  for (const [k, v] of [...url.searchParams]) url.searchParams.set(k, undated(v));
  return {
    method: req.method,
    url: url.toString(),
    ...(req.body === undefined ? {} : { body: walk(req.body, undated) }),
  };
}

const FIXTURE_DIRS: Record<string, string> = {
  "api.duffel.com": "duffel",
  "api.viator.com": "viator",
  "www.ecb.europa.eu": "ecb",
};

export function fixturePath(dir: string, req: HttpRequest): string {
  const material = fixtureKeyMaterial(req);
  const hash = createHash("sha256").update(JSON.stringify(material)).digest("hex").slice(0, 16);
  const host = new URL(req.url).hostname;
  return join(dir, FIXTURE_DIRS[host] ?? host, `${hash}.json`);
}

const toDay = (iso: string) => Date.parse(`${iso}T00:00:00Z`);

/**
 * Moves every date in `body` by the offset of the closest recorded request date, so an
 * outbound flight follows the new departure date and the return follows the new return date.
 */
export function shiftDates(body: unknown, recorded: string[], requested: string[]): unknown {
  const pairs = recorded
    .map((r, i) => [toDay(r), requested[i] ? toDay(requested[i]) : NaN] as const)
    .filter(([r, q]) => !Number.isNaN(r) && !Number.isNaN(q));
  if (pairs.length === 0) return body;
  return walk(body, (s) => {
    const m = DATE_RE.exec(s);
    if (!m?.[1]) return s;
    const day = toDay(m[1]);
    if (Number.isNaN(day)) return s;
    const [from, to] = pairs.reduce((best, p) =>
      Math.abs(p[0] - day) < Math.abs(best[0] - day) ? p : best,
    );
    const shifted = new Date(day + (to - from)).toISOString().slice(0, 10);
    return `${shifted}${m[2] ?? ""}`;
  });
}

/**
 * Live Duffel offer and search-result IDs are unique per search. One recording replayed for
 * several date pairs would repeat them, so the requested dates are appended on replay.
 */
const PER_SEARCH_ID = /^(off|srr)_[A-Za-z0-9]+$/;

function saltIds(body: unknown, salt: string): unknown {
  return salt ? walk(body, (s) => (PER_SEARCH_ID.test(s) ? `${s}${salt}` : s)) : body;
}

/** Serves recorded responses. A missing fixture is a 404, logged with what to record. */
export function fixtureTransport(
  dir: string,
  log: (msg: string) => void = console.warn,
): Transport {
  return async (req) => {
    const path = fixturePath(dir, req);
    if (!existsSync(path)) {
      log(`No fixture for ${req.method} ${req.url} (${path}); run the fixture recorder.`);
      return { status: 404, headers: {}, body: { errors: [{ title: "fixture not found" }] } };
    }
    const fixture = JSON.parse(readFileSync(path, "utf8")) as Fixture;
    const dates = requestDates(req);
    const shifted = shiftDates(fixture.response.body, fixture.recorded_dates, dates);
    return { ...fixture.response, body: saltIds(shifted, dates.join("").replaceAll("-", "")) };
  };
}

/** Wraps a transport and writes every exchange to `dir`. Request headers are never stored. */
export function recordingTransport(inner: Transport, dir: string, synthetic = false): Transport {
  return async (req, signal) => {
    const res = await inner(req, signal);
    const path = fixturePath(dir, req);
    mkdirSync(dirname(path), { recursive: true });
    const fixture: Fixture = {
      request: fixtureKeyMaterial(req),
      recorded_dates: requestDates(req),
      ...(synthetic ? { synthetic: true } : {}),
      response: res,
    };
    // One line per fixture keeps the directory small; pipe through jq to read one.
    writeFileSync(path, `${JSON.stringify(fixture)}\n`);
    return res;
  };
}

/** Finds the repo's fixtures/ directory by walking up from `from`. */
export function findFixturesDir(from = process.cwd()): string {
  let dir = resolve(from);
  for (;;) {
    const candidate = join(dir, "fixtures");
    if (existsSync(candidate) && statSync(candidate).isDirectory()) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return join(resolve(from), "fixtures");
    dir = parent;
  }
}
